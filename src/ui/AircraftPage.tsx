import { useMemo, useState } from "react";
import type { AutoTrack, FlightPlan, ScenarioAircraft, StartingConditions, StartType } from "../core/types";
import { describeStart, fmtTime } from "../core/position";
import { ulid } from "../core/ulid";
import { addAircraft, removeAircraft, setState, updateAircraft, useStore } from "../state/store";
import { MapView } from "./MapView";
import { Area, Card, Check, Empty, Field, FixInput, Num, PositionSelect, Select, Text } from "./widgets";

const START_TYPES: { value: StartType; label: string }[] = [
  { value: "Parking", label: "Parked at a gate" },
  { value: "OnRunway", label: "On the runway" },
  { value: "OnFinal", label: "On final" },
  { value: "FixOrFrd", label: "At a fix" },
  { value: "Coordinates", label: "At coordinates" },
];

const EMPTY_PLAN: FlightPlan = { rules: "IFR", departure: "", destination: "", cruiseAltitude: 0, cruiseSpeed: 0, route: "", remarks: "/v/", aircraftType: "" };

function blankAircraft(airportId: string): ScenarioAircraft {
  return {
    id: ulid(),
    aircraftId: "N" + Math.floor(100 + Math.random() * 900) + "CB",
    aircraftType: "C172",
    transponderMode: "C",
    startingConditions: { type: "Parking" },
    onAltitudeProfile: false,
    flightplan: { ...EMPTY_PLAN, aircraftType: "C172" },
    presetCommands: [],
    airportId: airportId || undefined,
    difficulty: "Easy",
  };
}

function Editor({ a }: { a: ScenarioAircraft }) {
  const parking = useStore((s) => s.maps[a.airportId ?? ""]?.parking);
  const ruleName = useStore((s) => s.project.rules.find((r) => r.id === s.project.generatedBy[a.id])?.name);
  const set = (patch: Partial<ScenarioAircraft>) => updateAircraft(a.id, (x) => ({ ...x, ...patch }));
  const st = a.startingConditions;
  const setStart = (patch: Partial<StartingConditions>) => set({ startingConditions: { ...st, ...patch } });
  const fp = a.flightplan;
  const setPlan = (patch: Partial<FlightPlan>) => set({ flightplan: { ...(fp ?? EMPTY_PLAN), ...patch } });
  const at = a.autoTrackConditions;
  const setTrack = (patch: Partial<AutoTrack>) => set({ autoTrackConditions: { ...(at ?? { positionId: "" }), ...patch } });
  const opt = (v: string) => v || undefined;

  return (
    <Card
      title={a.aircraftId || "Aircraft"}
      actions={
        <>
          <button className="small" onClick={() => addAircraft({ ...structuredClone(a), id: ulid(), aircraftId: a.aircraftId + "X" })}>
            Duplicate
          </button>
          <button className="small danger" onClick={() => removeAircraft([a.id])}>
            Delete
          </button>
        </>
      }
    >
      {ruleName && <p className="note">Generated by rule “{ruleName}”. Editing detaches it, so regenerating the rule won't overwrite your changes.</p>}
      <div className="form">
        <Field label="Callsign">
          <Text value={a.aircraftId} onChange={(aircraftId) => set({ aircraftId })} upper />
        </Field>
        <Field label="Type" hint="With equipment suffix, e.g. B738/L">
          <Text
            value={a.aircraftType}
            onChange={(aircraftType) => set({ aircraftType, flightplan: fp ? { ...fp, aircraftType } : fp })}
            upper
          />
        </Field>
        <Field label="Airport" hint="FAA id">
          <Text value={a.airportId ?? ""} onChange={(v) => set({ airportId: opt(v) })} upper />
        </Field>
        <Field label="Spawn delay (s)">
          <Num value={a.spawnDelay ?? 0} min={0} onChange={(v) => set({ spawnDelay: v || undefined })} />
        </Field>
        <Field label="Transponder">
          <Select value={a.transponderMode} onChange={(transponderMode) => set({ transponderMode })} options={["C", "Standby"]} />
        </Field>
        <Field label="Pilot difficulty">
          <Select value={a.difficulty ?? "Easy"} onChange={(difficulty) => set({ difficulty })} options={["Easy", "Medium", "Hard"]} />
        </Field>

        <h3>Starting position</h3>
        <Field label="Start" wide>
          <Select value={st.type} onChange={(type) => set({ startingConditions: { type } })} options={START_TYPES} />
        </Field>
        {st.type === "Parking" && (
          <Field label="Gate" wide hint={parking ? `${parking.length} spots on the map` : "No gate map loaded for this airport"}>
            <Text value={st.parking ?? ""} onChange={(v) => setStart({ parking: opt(v) })} list="gate-list" mono />
            <datalist id="gate-list">
              {parking?.map((p) => (
                <option key={p.name} value={p.name} />
              ))}
            </datalist>
          </Field>
        )}
        {(st.type === "OnRunway" || st.type === "OnFinal") && (
          <Field label="Runway">
            <Text value={st.runway ?? ""} onChange={(v) => setStart({ runway: opt(v) })} upper />
          </Field>
        )}
        {st.type === "OnFinal" && (
          <Field label="Distance from runway (nm)">
            <Num value={st.distanceFromRunway} min={0} onChange={(v) => setStart({ distanceFromRunway: v ?? undefined })} />
          </Field>
        )}
        {st.type === "FixOrFrd" && (
          <Field label="Fix or FRD">
            <FixInput value={st.fix ?? ""} onChange={(v) => setStart({ fix: opt(v) })} />
          </Field>
        )}
        {st.type === "Coordinates" && (
          <>
            <Field label="Latitude">
              <Num value={st.coordinates?.lat} step={0.01} onChange={(v) => setStart({ coordinates: { lat: v ?? 0, lon: st.coordinates?.lon ?? 0 } })} />
            </Field>
            <Field label="Longitude">
              <Num value={st.coordinates?.lon} step={0.01} onChange={(v) => setStart({ coordinates: { lat: st.coordinates?.lat ?? 0, lon: v ?? 0 } })} />
            </Field>
          </>
        )}
        {(st.type === "FixOrFrd" || st.type === "Coordinates") && (
          <>
            <Field label="Altitude (ft)">
              <Num value={st.altitude} step={1000} onChange={(v) => setStart({ altitude: v ?? undefined })} />
            </Field>
            <Field label="Speed (kt)">
              <Num value={st.speed} step={10} onChange={(v) => setStart({ speed: v || undefined })} />
            </Field>
            <Field label="Heading" hint="Used when there is no navigation path">
              <Num value={st.heading} min={0} onChange={(v) => setStart({ heading: v ?? undefined })} />
            </Field>
            <Field label="Navigation path" wide>
              <Text value={st.navigationPath ?? ""} onChange={(v) => setStart({ navigationPath: opt(v) })} upper />
            </Field>
            <Field label="Altitude profile" wide>
              <Check checked={a.onAltitudeProfile} onChange={(onAltitudeProfile) => set({ onAltitudeProfile })} label="Descend on the procedure's published altitudes" />
            </Field>
          </>
        )}

        <h3>Flight plan</h3>
        <Field label="Filed" wide>
          <Check checked={!!fp} onChange={(on) => set({ flightplan: on ? { ...EMPTY_PLAN, aircraftType: a.aircraftType } : undefined })} label="Aircraft has a flight plan" />
        </Field>
        {fp && (
          <>
            <Field label="Rules">
              <Select value={fp.rules} onChange={(rules) => setPlan({ rules })} options={["IFR", "VFR"]} />
            </Field>
            <Field label="Cruise altitude (ft)">
              <Num value={fp.cruiseAltitude} step={1000} onChange={(v) => setPlan({ cruiseAltitude: v ?? 0 })} />
            </Field>
            <Field label="Departure">
              <Text value={fp.departure} onChange={(departure) => setPlan({ departure })} upper />
            </Field>
            <Field label="Destination">
              <Text value={fp.destination} onChange={(destination) => setPlan({ destination })} upper />
            </Field>
            <Field label="Route" wide>
              <Area value={fp.route} onChange={(route) => setPlan({ route: route.toUpperCase() })} rows={2} />
            </Field>
            <Field label="Remarks" wide>
              <Text value={fp.remarks} onChange={(remarks) => setPlan({ remarks })} mono />
            </Field>
          </>
        )}

        <h3>Behaviour</h3>
        <Field label="Preset commands, one per line" wide>
          <Area
            value={a.presetCommands.map((c) => c.command).join("\n")}
            rows={3}
            onChange={(text) =>
              set({
                presetCommands: text.split("\n").map((command, i) => ({
                  id: a.presetCommands[i]?.id ?? ulid(),
                  command,
                  timeOffset: a.presetCommands[i]?.timeOffset ?? 0,
                })),
              })
            }
          />
        </Field>
        <Field label="Start tracked by" wide>
          <PositionSelect value={at?.positionId ?? ""} onChange={(v) => set({ autoTrackConditions: v ? { ...at, positionId: v } : undefined })} />
        </Field>
        {at && (
          <>
            <Field label="Handoff after (s)">
              <Num value={at.handoffDelay} min={0} onChange={(v) => setTrack({ handoffDelay: v ?? undefined })} />
            </Field>
            <Field label="Scratchpad">
              <Text value={at.scratchPad ?? ""} onChange={(v) => setTrack({ scratchPad: opt(v) })} upper />
            </Field>
            <Field label="Interim altitude">
              <Text value={at.interimAltitude ?? ""} onChange={(v) => setTrack({ interimAltitude: opt(v) })} upper />
            </Field>
            <Field label="Cleared altitude">
              <Text value={at.clearedAltitude ?? ""} onChange={(v) => setTrack({ clearedAltitude: opt(v) })} upper />
            </Field>
          </>
        )}
        <Field label="Expected approach">
          <Text value={a.expectedApproach ?? ""} onChange={(v) => set({ expectedApproach: opt(v) })} upper />
        </Field>
      </div>
    </Card>
  );
}

export function AircraftPage() {
  const project = useStore((s) => s.project);
  const selectedId = useStore((s) => s.selectedAircraftId);
  const [filter, setFilter] = useState("");
  const all = project.scenario.aircraft;
  const ruleNames = useMemo(() => new Map(project.rules.map((r) => [r.id, r.name])), [project.rules]);

  const rows = useMemo(() => {
    const q = filter.trim().toUpperCase();
    const list = q
      ? all.filter((a) => [a.aircraftId, a.aircraftType, a.flightplan?.departure, a.flightplan?.destination, a.flightplan?.route, describeStart(a)].join(" ").toUpperCase().includes(q))
      : all;
    return [...list].sort((x, y) => (x.spawnDelay ?? 0) - (y.spawnDelay ?? 0));
  }, [all, filter]);
  const selected = all.find((a) => a.id === selectedId);

  return (
    <div className="grid side wide-left">
      <div className="stack">
        <Card
          title={`Aircraft (${all.length})`}
          actions={
            <>
              <input type="search" placeholder="Filter" value={filter} onChange={(e) => setFilter(e.target.value)} />
              <button className="small primary" onClick={() => addAircraft(blankAircraft(project.scenario.primaryAirportId ?? ""))}>
                + Add aircraft
              </button>
            </>
          }
        >
          {all.length === 0 ? (
            <Empty>No aircraft yet. Generate some from the Traffic rules tab, or add one by hand.</Empty>
          ) : (
            <div className="table-wrap">
              <table className="table click">
                <thead>
                  <tr>
                    <th>Spawn</th>
                    <th>Callsign</th>
                    <th>Type</th>
                    <th>Start</th>
                    <th>From → To</th>
                    <th>Route</th>
                    <th>Source</th>
                  </tr>
                </thead>
                <tbody>
                  {rows.map((a) => (
                    <tr key={a.id} className={a.id === selectedId ? "on" : ""} onClick={() => setState({ selectedAircraftId: a.id })}>
                      <td className="mono">{fmtTime(a.spawnDelay)}</td>
                      <td className="mono strong">{a.aircraftId}</td>
                      <td className="mono">{a.aircraftType}</td>
                      <td>{describeStart(a)}</td>
                      <td className="mono">{a.flightplan ? `${a.flightplan.departure || "—"} → ${a.flightplan.destination || "—"}` : "no plan"}</td>
                      <td className="mono clip" title={a.flightplan?.route}>
                        {a.startingConditions.navigationPath || a.flightplan?.route}
                      </td>
                      <td className="muted">{ruleNames.get(project.generatedBy[a.id]) ?? "manual"}</td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          )}
        </Card>
        <MapView aircraft={all} />
      </div>
      <div>{selected ? <Editor key={selected.id} a={selected} /> : <Card title="No aircraft selected">{<Empty>Select a row or a map marker to edit it.</Empty>}</Card>}</div>
    </div>
  );
}
